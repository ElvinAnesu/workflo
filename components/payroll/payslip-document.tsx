import { formatMoney } from "@/components/payroll/payroll-format";
import { formatPeriod } from "@/components/payroll/payroll-run-builder";
import type { PayrollLine, PayrollRun } from "@/components/payroll/payroll.types";

type PayslipDocumentProps = {
  run: Pick<PayrollRun, "period" | "status"> & { lockedOn?: string };
  line: PayrollLine & { employeeCode?: string };
  companyName: string;
  companyAddress: string;
};

function Row({ label, value, strong }: { label: string; value: number; strong?: boolean }) {
  return (
    <tr className={strong ? "border-t border-zinc-300 font-semibold text-zinc-900" : "text-zinc-700"}>
      <td className="py-1 pr-4">{label}</td>
      <td className="py-1 text-right tabular-nums">{formatMoney(value)}</td>
    </tr>
  );
}

export function PayslipDocument({
  run,
  line,
  companyName,
  companyAddress,
}: PayslipDocumentProps) {
  const isFinal = run.status === "Locked";
  const footer = isFinal
    ? run.lockedOn
      ? `Generated by Workflo · payroll locked on ${run.lockedOn}`
      : "Generated by Workflo"
    : "This payslip is not final. It may change until the payroll is locked.";
  const employeeDeductions = line.contributions.filter((item) => item.employee > 0);
  const employerItems = line.contributions.filter((item) => item.employer > 0);

  return (
    <article className="relative mx-auto flex w-full max-w-3xl flex-col gap-5 overflow-hidden rounded-lg border border-zinc-200 bg-white p-8 text-xs break-after-page print:max-w-none print:rounded-none print:border-0 print:p-0">
      {!isFinal ? (
        <span className="pointer-events-none absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 -rotate-12 text-6xl font-black tracking-widest text-zinc-100 uppercase select-none">
          {run.status === "Draft" ? "Draft" : "Not final"}
        </span>
      ) : null}

      <header className="relative flex items-start justify-between gap-4 border-b-2 border-[#172554] pb-4">
        <div>
          <p className="text-base font-bold text-[#172554]">{companyName || "Company name not set"}</p>
          {companyAddress ? <p className="text-zinc-500">{companyAddress}</p> : null}
        </div>
        <div className="text-right">
          <p className="text-sm font-semibold tracking-wide text-zinc-900 uppercase">Payslip</p>
          <p className="text-zinc-600">{formatPeriod(run.period)}</p>
        </div>
      </header>

      <section className="relative grid grid-cols-2 gap-x-8 gap-y-1.5">
        {[
          ["Employee name", line.employeeName],
          ["Employee code", line.employeeCode || line.employeeId],
          ["Designation", line.designation],
          ["Department", line.department],
          ["Bank", line.bankName],
          ["Account number", line.accountNumber],
        ].map(([label, value]) => (
          <div key={label} className="flex justify-between gap-3 border-b border-zinc-100 py-1">
            <span className="text-zinc-500">{label}</span>
            <span className="text-right font-medium text-zinc-900">{value || "—"}</span>
          </div>
        ))}
      </section>

      <section className="relative grid grid-cols-2 gap-8">
        <div>
          <h3 className="mb-1 bg-zinc-100 px-2 py-1 font-semibold text-zinc-800">Earnings</h3>
          <table className="w-full border-collapse">
            <tbody>
              <Row label="Basic salary" value={line.basicSalary} />
              {line.earnings.map((item) => (
                <Row
                  key={item.componentId}
                  label={`${item.name}${item.taxable ? "" : " (non-taxable)"}`}
                  value={item.amount}
                />
              ))}
              <Row label="Gross pay" value={line.grossPay} strong />
            </tbody>
          </table>
        </div>
        <div>
          <h3 className="mb-1 bg-zinc-100 px-2 py-1 font-semibold text-zinc-800">Deductions</h3>
          <table className="w-full border-collapse">
            <tbody>
              {employeeDeductions.map((item) => (
                <Row key={item.contributionId} label={item.name} value={item.employee} />
              ))}
              <Row label="PAYE" value={line.paye} />
              {line.deductions.map((item) => (
                <Row key={item.componentId} label={item.name} value={item.amount} />
              ))}
              <Row label="Total deductions" value={line.totalDeductions} strong />
            </tbody>
          </table>
        </div>
      </section>

      <section className="relative flex items-center justify-between rounded-md bg-[#172554] px-4 py-3 text-white">
        <span className="text-sm font-semibold">Net pay</span>
        <span className="text-lg font-bold tabular-nums">{formatMoney(line.netPay)}</span>
      </section>

      <section className="relative grid grid-cols-2 gap-8 text-zinc-600">
        <div className="flex justify-between">
          <span>Taxable income</span>
          <span className="tabular-nums">{formatMoney(line.taxableIncome)}</span>
        </div>
        {employerItems.length > 0 ? (
          <div>
            <p className="mb-1 font-medium text-zinc-700">Employer contributions (not deducted)</p>
            {employerItems.map((item) => (
              <div key={item.contributionId} className="flex justify-between">
                <span>{item.name}</span>
                <span className="tabular-nums">{formatMoney(item.employer)}</span>
              </div>
            ))}
          </div>
        ) : null}
      </section>

      {line.held ? (
        <p className="relative rounded-md bg-indigo-50 px-3 py-2 text-indigo-800">
          Payment of this salary is on hold{line.holdReason ? `: ${line.holdReason}` : ""}.
        </p>
      ) : null}

      <footer className="relative border-t border-zinc-200 pt-3 text-[10px] text-zinc-400">
        {footer}
      </footer>
    </article>
  );
}
